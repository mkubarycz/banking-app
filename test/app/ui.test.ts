import assert from 'node:assert/strict';
import test from 'node:test';
import { bankingUi } from '../../src/app/ui.js';

test('renders a syntactically valid continuous spreadsheet-style ledger editor', () => {
  const script = bankingUi.match(/<script>([\s\S]*)<\/script>/)?.[1];
  assert.ok(script);
  assert.doesNotThrow(() => new Function(script));
  assert.match(bankingUi, />Ledger<\/button>/);
  assert.match(bankingUi, />Budget Pacing<\/button>/);
  assert.match(bankingUi, /<h2>Continuous ledger<\/h2>/);
  assert.match(bankingUi, /id="filter-from"/);
  assert.match(bankingUi, /id="filter-through"/);
  assert.match(bankingUi, /id="filter-status"/);
  assert.match(bankingUi, /id="filter-search"/);
  assert.match(bankingUi, /<option value="__not-realized__">Not Realized<\/option>/);
  assert.match(bankingUi, /status==='__not-realized__'\?e\.spec\.status!=='Realized'/);
  assert.match(bankingUi, /setThisYear\(\);load\(\)/);
  assert.match(bankingUi, /currentYear\(\)\+'\-12\-31'/);
  assert.doesNotMatch(bankingUi, /id="year"/);
  assert.doesNotMatch(bankingUi, /Same-day order/);
  assert.doesNotMatch(bankingUi, /Dirty changes/);
  assert.doesNotMatch(bankingUi, /Commit selected/);
  assert.doesNotMatch(bankingUi, /Discard selected/);
  assert.match(bankingUi, /id="dirty-filter"/);
  assert.match(bankingUi, /Dirty '\+\(count===1\?'Row':'Rows'\)/);
  assert.match(bankingUi, /dirtyOnly\?dirtyEntries:entries/);
  assert.match(bankingUi, /previous-row/);
  assert.match(bankingUi, />Committed<\/th>/);
  assert.match(bankingUi, /src="\/vendor\/timeago\.min\.js"/);
  assert.match(bankingUi, /timeago\.register\('ledger'/);
  assert.match(bankingUi, /\['Just now','Right now'\],\['Just now','Right now'\]/);
  assert.match(bankingUi, /age<7\*24\*60\*60\*1000/);
  assert.match(bankingUi, /const nodes=\[\.\.\.document\.querySelectorAll\('time\.timeago'\)\]/);
  assert.match(bankingUi, /if\(nodes\.length\)timeago\.render\(nodes,'ledger'/);
  assert.match(bankingUi, /modifiedTimeHtml\(e\.status\.committedAt\)/);
  assert.match(bankingUi, /class="row-config-menu"/);
  assert.match(bankingUi, />Delete row<\/button>/);
  assert.match(bankingUi, />Commit<\/button>/);
  assert.match(bankingUi, />Revert<\/button>/);
  assert.match(bankingUi, /\.row-state button\{width:84px\}/);
  assert.doesNotMatch(bankingUi, /colspan="8"/);
  assert.match(bankingUi, /dirty-row/);
  assert.match(bankingUi, /Click a cell to edit/);
  assert.match(bankingUi, /data-field="/);
  assert.doesNotMatch(bankingUi, />Edit<\/button>/);
  assert.doesNotMatch(bankingUi, />Delete<\/button>/);
});
